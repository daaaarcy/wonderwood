#!/usr/bin/env node
/**
 * Copies the shared domain + data modules into supabase/functions/_shared
 * (gitignored) so the Deno edge function can bundle them. src/ stays the
 * single source of truth; this runs automatically on `test` and `deploy:game`.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const FILES = [
  'types.ts',
  'avatar.ts',
  'state.ts',
  'week.ts',
  'migrate.ts',
  'challenge.ts',
  'weekly.ts',
  'commands.ts',
  'quests.ts',
  'catalogue.ts',
  'city.ts',
]
const SRC = { 'types.ts': 'src/domain', 'avatar.ts': 'src/domain', 'state.ts': 'src/domain', 'week.ts': 'src/domain', 'commands.ts': 'src/domain', 'migrate.ts': 'src/domain', 'challenge.ts': 'src/domain', 'weekly.ts': 'src/data',
              'quests.ts': 'src/data', 'catalogue.ts': 'src/data', 'city.ts': 'src/data' }
const OUT = 'supabase/functions/_shared'

mkdirSync(OUT, { recursive: true })
for (const f of FILES) {
  let s = readFileSync(join(SRC[f], f), 'utf8')
  // flatten: '../domain/x.ts' and '../data/x.ts' → './x.ts'
  s = s.replace(/from '\.\.\/(domain|data)\//g, "from './")
  writeFileSync(join(OUT, f), s)
  console.log(`synced ${f}`)
}
writeFileSync(
  join(OUT, 'deps.ts'),
  `// generated by scripts/sync-shared.mjs — wires data lookups into CommandDeps
import type { CommandDeps } from './types.ts'
import { questById } from './quests.ts'
import { itemById } from './catalogue.ts'
import { projectById } from './city.ts'

export const commandDeps: CommandDeps = {
  getQuest: (questId) => questById(questId),
  getItem: (itemId) => itemById(itemId),
  getProject: (projectId) => projectById(projectId),
}
`,
)
console.log('synced deps.ts')
